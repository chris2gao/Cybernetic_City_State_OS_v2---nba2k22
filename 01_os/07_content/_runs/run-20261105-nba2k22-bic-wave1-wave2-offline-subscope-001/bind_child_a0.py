"""Apply the published child A0 approval to the fixed pre-binding Run."""
import argparse
import hashlib
import importlib.util
import json
import subprocess
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[3]
RUN = OUT.relative_to(ROOT).as_posix()
BASE = "a9a9a444907c6b35aa6bcd4da5c7f123cba522e9"
CORE_SHA = "08d8e534a3438269aa7d7eb1b080ab11c172f462"
APPROVAL = "7428864602f7d29ee9620db36b7b975f3e2b70c8"
CONTRACT = "dd7c4c6ae0fb7ced486a7255589ee8a9f9349524"
SOURCE_ROOT = "01_os/07_content/_runs/run-20261105-nba2k22-bic-scoped-a0-human-confirmation-001/"
APPROVAL_PATH = SOURCE_ROOT + "HUMAN_CHILD_A0_CONFIRMATION_20261105.json"
A0_DIGEST = "908827305fd94f67a902e79830f08bebaea5f26dc0aade073f5fe647748a46c9"
OLD_A_DIGEST = "c8184084a9229cedc67de04735a481d387f121561ea4e7be0de0592396ad5b93"
RUNNER = "01_os/06_execution/workflow/minimum_operational_loop/run_minimum_operational_loop.py"
DEFAULT_CORE = Path("C:/Users/gk/.codex/worktrees/nba2k22-bic-os-core-08d8e534")


def git(*args, repo=ROOT):
    return subprocess.check_output(["git", "-C", str(repo), *args])


def original(name):
    return git("show", f"{BASE}:{RUN}/{name}")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--core-root", type=Path, default=DEFAULT_CORE)
    parser.add_argument("--check", action="store_true", help="Compare the generated bytes without writing")
    args = parser.parse_args()
    assert git("rev-parse", "HEAD", repo=args.core_root).decode().strip() == CORE_SHA
    runner_path = args.core_root / RUNNER
    runner_bytes = git("show", f"{CORE_SHA}:{RUNNER}", repo=args.core_root)
    assert runner_path.read_bytes() == runner_bytes
    spec = importlib.util.spec_from_file_location("a0_binding_core", runner_path)
    core = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(core)

    confirmation_ref = f"{APPROVAL}:{APPROVAL_PATH}"
    approval_bytes = git("show", confirmation_ref)
    approval = json.loads(approval_bytes)
    manifest = yaml.safe_load(original("manifest.yml"))
    requirement = yaml.safe_load(original("01_requirement.yml"))
    payload = requirement["payload"]
    a0 = payload["consensus_A0"]
    criteria = payload["success_criteria"]
    criterion_ids = [item["criterion_id"] for item in criteria]
    assert criterion_ids == [f"OFF-SC{index:02d}" for index in range(1, 8)]
    assert approval["status"] == "HUMAN_CONFIRMED_FIXED_CHILD_A0_V1"
    assert approval["fixed_binding"] == {
        "child_run_id": OUT.name, "child_candidate_commit": BASE,
        "model_kind": "consensus_A0", "model_id": a0["model_id"],
        "artifact_version": a0["version"], "normalized_sha256": A0_DIGEST,
        "original_candidate_file": f"{RUN}/01_requirement.yml",
        "original_digest_file": f"{RUN}/NORMALIZED_BINDINGS.json",
        "acceptance_criterion_ids": criterion_ids,
    }
    assert a0["model_id"] == "NBA2K22-BIC-W1-W2-OFFLINE-A0-001" and a0["version"] == 1
    assert core.normalized_sha256(a0) == A0_DIGEST
    assert core.requirement_confirmation_digest(payload) == OLD_A_DIGEST
    charter = json.loads(original("sources/W1_W2_SCOPED_RUN_CHARTER_CANDIDATE_v1.json"))
    assert a0["boundaries"] == payload["constraints"] == charter["explicit_exclusions"]
    assert [(item["criterion_id"], item["statement"]) for item in criteria] == [
        (item["id"], item["required"]) for item in charter["acceptance_criteria_candidate"]
    ]
    assert approval["approved_exact_scope"]["parent_requirement_status"] == "INCOMPLETE_UNCHANGED"
    assert approval["approval_to_complete_stage01"] is False
    assert "Requirement Result A confirmation or the provisional A digest" in approval["NOT_APPROVED"]
    assert "master integration, protected branch writes, game process access or Native/REA writes" in approval["NOT_APPROVED"]
    assert payload["Human_confirmation"]["confirmed"] is False
    assert payload["Human_confirmation"]["confirmation_ref"] is None
    assert payload["consensus_Human_confirmation"]["confirmed"] is False
    payload["consensus_Human_confirmation"].update(
        confirmed=True, confirmation_ref=confirmation_ref, status="HUMAN_CONFIRMED_FIXED_CHILD_A0_V1"
    )
    payload["requirement_result_A"]["consensus_ref"] = {
        "model_id": a0["model_id"], "version": a0["version"],
        "sha256": A0_DIGEST, "confirmation_ref": confirmation_ref,
    }
    child_a_digest = core.requirement_confirmation_digest(payload)
    assert child_a_digest != OLD_A_DIGEST
    payload["Human_confirmation"]["content_sha256"] = child_a_digest

    outputs = {}
    previous = {}
    changes = []
    for entry in manifest["artifacts"]:
        path = entry["path"]
        raw_before = original(path)
        assert digest(raw_before) == entry["sha256"]
        artifact = requirement if path == "01_requirement.yml" else yaml.safe_load(raw_before)
        artifact["input_refs"] = [previous[ref["stage_id"]].copy() for ref in artifact["input_refs"]]
        raw_after = yaml.safe_dump(artifact, allow_unicode=True, sort_keys=False, width=4096).encode()
        changes.append({"path": path, "old_sha256": entry["sha256"], "new_sha256": digest(raw_after),
                        "input_refs": artifact["input_refs"]})
        entry["sha256"] = digest(raw_after)
        previous[entry["stage_id"]] = entry.copy()
        outputs[path] = raw_after
    outputs["manifest.yml"] = yaml.safe_dump(manifest, sort_keys=False).encode()
    outputs["sources/HUMAN_CHILD_A0_CONFIRMATION_20261105.json"] = approval_bytes
    contract_path = SOURCE_ROOT + "EXECUTION_CONTRACT_A0_BIND_PREPARE_A_20261105.md"
    contract_bytes = git("show", f"{CONTRACT}:{contract_path}")
    assert approval["explicit_human_statement"] in contract_bytes.decode("utf-8")
    review_commit = "95d871848ae99e97393e34c66941b577bff86336"
    review_path = ("01_os/07_content/_runs/run-20261105-nba2k22-bic-scoped-os-owner-preflight-review-001/"
                   "OWNER_ADMISSION_PREFLIGHT_HUMAN_REPORT.md")
    review_bytes = git("show", f"{review_commit}:{review_path}")
    approval_source = {
        "commit": APPROVAL, "path": APPROVAL_PATH,
        "git_blob": git("rev-parse", confirmation_ref).decode().strip(),
        "sha256": digest(approval_bytes), "copy": "sources/HUMAN_CHILD_A0_CONFIRMATION_20261105.json",
    }
    bindings = json.loads(original("NORMALIZED_BINDINGS.json"))
    bindings["superseded_provisional_child_A_sha256"] = bindings.pop("child_A_payload_provisional_sha256")
    bindings.update(child_A_payload_sha256=child_a_digest, child_A0_confirmed=True,
                    child_A0_confirmation_ref=confirmation_ref, child_A0_approval_source=approval_source,
                    owner_sequence="Review and decide the exact child A v1 payload independently.",
                    status="PENDING_CHILD_A_CONFIRMATION")
    outputs["NORMALIZED_BINDINGS.json"] = json_bytes(bindings)
    owner = json.loads(original("OWNER_DECISION_PACKAGE.json"))
    owner.update(status="PENDING_CHILD_A_CONFIRMATION", candidate_artifacts=manifest["artifacts"],
                 single_gate="Separate Human confirmation of this exact child A v1",
                 next_Human_decision={"model_id": payload["requirement_id"], "artifact_version": 1,
                                      "content_sha256": child_a_digest, "candidate": "01_requirement.yml",
                                      "current_disposition": "NOT_ISSUED"},
                 child_A0_approval_source=approval_source)
    owner["decisions"][0].update(request="Review the complete child A v1 and decide on its fixed digest.",
                                  current_disposition="A0_CONFIRMED_CHILD_A_PENDING")
    outputs["OWNER_DECISION_PACKAGE.json"] = json_bytes(owner)
    checkpoint = json.loads(original("CHECKPOINT.json"))
    checkpoint.update(status="PENDING_CHILD_A_CONFIRMATION", binding_task_base_sha=BASE,
                      binding_task_id="NBA2K22-BIC-W1-W2-CHILD-A0-BIND-AND-A-PREPARE-20261105-001",
                      child_A0_confirmation_ref=confirmation_ref, child_A_payload_sha256=child_a_digest,
                      progress=["Fixed child A0 Human approval bound", "Child A and Stage01–07 hashes regenerated"],
                      next_steps=["Review CHILD_A_CONFIRMATION_HANDOFF.md and decide the exact child A v1"])
    outputs["CHECKPOINT.json"] = json_bytes(checkpoint)
    run_doc = yaml.safe_load(original("run.yml"))
    run_doc["formal_status"] = "PENDING_CHILD_A_CONFIRMATION"
    run_doc["closure_record"] = "CHILD_A_CONFIRMATION_HANDOFF.md"
    outputs["run.yml"] = yaml.safe_dump(run_doc, sort_keys=False).encode()
    stage_checks = json.loads(original("CANDIDATE_SCHEMA_CHECKS.json"))
    schemas = core.payload_schemas(args.core_root)
    for row in stage_checks["stages"]:
        sid = row["stage_id"]
        stage_payload = yaml.safe_load(outputs[previous[sid]["path"]])["payload"]
        row["missing_payload_fields"] = [
            field for field in schemas[sid]["payload_required_fields"] if field not in stage_payload
        ]
        row["type_findings"] = core.payload_type_findings(stage_payload, sid)
        assert not row["missing_payload_fields"] and not row["type_findings"], sid
    stage_checks["requirement_findings"] = core.requirement_findings(payload, 1)
    stage_checks["evidence_findings"] = core.evidence_findings(yaml.safe_load(outputs["02_evidence.yml"])["payload"], payload)
    print(json.dumps({"requirement_findings": stage_checks["requirement_findings"],
                      "evidence_findings": stage_checks["evidence_findings"]}))
    assert stage_checks["requirement_findings"] == ["stage1_confirmation_binding:requirement_result_A"]
    assert stage_checks["evidence_findings"] == []
    stage_checks["formal_full_run"] = "NOT_RUN_PENDING_CHILD_A_CONFIRMATION"
    outputs["CANDIDATE_SCHEMA_CHECKS.json"] = json_bytes(stage_checks)
    outputs["A0_BINDING_INTEGRITY.json"] = json_bytes({
        "base": BASE, "core_sha": CORE_SHA, "core_runner_sha256": digest(runner_bytes),
        "contract_source": {"commit": CONTRACT, "path": contract_path, "sha256": digest(contract_bytes)},
        "preparation_review_source": {"commit": review_commit, "path": review_path,
                                      "sha256": digest(review_bytes)},
        "approval_source": approval_source, "child_A0_sha256": A0_DIGEST, "child_A_sha256": child_a_digest,
        "criterion_ids": criterion_ids, "artifacts": changes, "manifest_sha256": digest(outputs["manifest.yml"]),
        "formal_stage01_pass": False, "status": "PENDING_CHILD_A_CONFIRMATION",
    })
    for path, data in outputs.items():
        if args.check:
            assert (OUT / path).read_bytes() == data, path
        else:
            (OUT / path).write_bytes(data)
    print(json.dumps({"mode": "check" if args.check else "write", "child_A0_sha256": A0_DIGEST,
                      "child_A_sha256": child_a_digest, "artifact_count": len(changes),
                      "status": "PENDING_CHILD_A_CONFIRMATION"}))


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


if __name__ == "__main__":
    main()
