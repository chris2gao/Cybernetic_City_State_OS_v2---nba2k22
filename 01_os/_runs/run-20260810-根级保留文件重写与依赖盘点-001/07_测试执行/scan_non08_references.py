#!/usr/bin/env python3
"""Enumerate every reference from the live surface to a path outside 01_os/**.

The live surface is deliberately narrow, because that is the question this run
has to answer: after the root rewrite, what still reaches out of the new OS?

  live surface = 01_os/** minus 01_os/_runs/**   (active OS: canonical, registry,
                                                  workflow, mechanisms, execution, _dev)
              + the seven rewritten retained root files
              + the four retained .githooks infrastructure files

01_os/_runs/** is excluded because run evidence records what a past task did; it
is not something the system loads. Its references are reported separately as a
count only, so their absence from the live set is a measurement rather than an
assumption.

A reference is an exact substring occurrence of a tracked non-08 path, or of a
non-08 directory prefix. Substring matching over-reports rather than under-reports
(a path named inside a longer path still counts), which is the safe direction for
a retention decision: a false edge costs a sentence of explanation, a missed edge
costs a deleted dependency.

Usage
    python scan_non08_references.py [--repo-root .] [--out <yaml>]
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REWRITTEN = [
    "AGENTS.md",
    "AGENT_WORKING_DISCIPLINE.md",
    "GEMINI.md",
    "CLAUDE.md",
    "README.md",
    "CORE_MANIFEST.yml",
    ".githooks/README.md",
]
FROZEN_INFRA = [
    ".githooks/pre-push",
    ".githooks/install.ps1",
    ".githooks/test_pre_push_logic.ps1",
    ".githooks/.gitattributes",
]


def git(*args: str) -> str:
    out = subprocess.run(
        ["git", *args], capture_output=True, text=True, encoding="utf-8"
    )
    if out.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {out.stderr.strip()}")
    return out.stdout


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--out", default="")
    args = parser.parse_args()
    root = Path(args.repo_root).resolve()

    tracked = [p for p in git("ls-files").splitlines() if p]
    non08 = [p for p in tracked if not p.startswith("01_os/")]
    non08_dirs = set()
    for path in non08:
        parts = path.split("/")
        for i in range(1, len(parts)):
            non08_dirs.add("/".join(parts[:i]) + "/")

    live = [
        p
        for p in tracked
        if p.startswith("01_os/") and not p.startswith("01_os/_runs/")
    ]
    live += REWRITTEN + FROZEN_INFRA
    runs = [p for p in tracked if p.startswith("01_os/_runs/")]

    texts: dict[str, str] = {}
    for rel in live:
        try:
            texts[rel] = (root / rel).read_text(encoding="utf-8", errors="replace")
        except (OSError, UnicodeDecodeError):
            continue

    targets = sorted(set(non08) | non08_dirs)
    edges: dict[str, list[str]] = defaultdict(list)
    for target in targets:
        for rel, text in texts.items():
            if target in text:
                edges[target].append(rel)

    run_edges: dict[str, int] = {}
    run_texts = {}
    for rel in runs:
        try:
            run_texts[rel] = (root / rel).read_text(encoding="utf-8", errors="replace")
        except (OSError, UnicodeDecodeError):
            continue
    for target in targets:
        count = sum(1 for text in run_texts.values() if target in text)
        if count:
            run_edges[target] = count

    lines = [
        "# Generated by 07_测试执行/scan_non08_references.py - do not hand-edit.",
        f"live_surface_files: {len(texts)}",
        f"run_evidence_files_scanned: {len(run_texts)}",
        f"non08_tracked_files: {len(non08)}",
        f"non08_targets_including_dirs: {len(targets)}",
        f"targets_referenced_by_live_surface: {len(edges)}",
        "",
        "referenced_by_live_surface:",
    ]
    for target in sorted(edges):
        lines.append(f"  - target: {target!r}")
        lines.append(f"    run_evidence_mentions: {run_edges.get(target, 0)}")
        lines.append("    referenced_by:")
        for rel in sorted(edges[target]):
            lines.append(f"      - {rel!r}")
    lines.append("")
    lines.append("# Targets with no live-surface reference are omitted; their count is")
    lines.append(f"# {len(targets) - len(edges)} of {len(targets)}.")

    out_text = "\n".join(lines) + "\n"
    if args.out:
        Path(args.out).write_text(out_text, encoding="utf-8")
        print(f"wrote {args.out}: {len(edges)} referenced targets "
              f"of {len(targets)}, live surface {len(texts)} files")
    else:
        print(out_text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
