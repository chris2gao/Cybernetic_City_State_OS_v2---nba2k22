"""Deterministic inventory of repository-path references rooted at ``08_os``.

The source tree is enumerated through ``git ls-files -z`` using a temporary index
loaded from an exact treeish. Blob bytes are then read from that same immutable
tree, so generated inventory artifacts cannot recursively add references to their
own input set.

Exit codes:
  0  complete scan and requested artifacts written
  2  invalid input or Git/YAML/output failure
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover - repository toolchain supplies PyYAML
    yaml = None


ROOT_NAME = "08" + "_os"
TARGET_ROOT = "01" + "_os"
REFERENCE_RE = re.compile(
    rf"(?<![A-Za-z0-9_])(?:\"{ROOT_NAME}\"|'{ROOT_NAME}'|"
    rf"{ROOT_NAME}(?:[/\\](?:\*\*)?[A-Za-z0-9_.*?{{}}\-\u0080-\uffff/\\]*))"
)
RUN_SEGMENT = "/_" + "runs/"
CODE_SUFFIXES = {".py", ".ps1", ".sh", ".js", ".ts", ".bat", ".cmd"}
DATA_SNAPSHOT_SUFFIXES = {".csv", ".txt", ".json", ".jsonl"}
BOUND_RECORD_MARKERS = (
    "schema_version:",
    "task_id:",
    "run_id:",
    "exact_base_sha:",
    "source_head:",
    "source_base:",
)
HISTORICAL_FACT_RE = re.compile(
    r"(?i)(?:\bhistorical\b|\blegacy\b|\bat the time\b|\bprevious(?:ly)?\b|"
    r"\bwas deleted\b|\bwere deleted\b|当时|此前|曾经|历史事实|旧系统|旧版|"
    r"删除回执|退役|迁移记录|原提交|源提交)"
)
ACTIVE_PATH_SYNTAX_RE = re.compile(
    r"(?i)(?:path|paths|root|loader|registry|manifest|boot|readme|link|glob|"
    r"allowlist|denylist|include|exclude|entry|startup|启动|入口|加载|注册|路径|目录)"
)
GENERATED_EVIDENCE_RE = re.compile(
    r"(?im)(?:^# Generated by |do not hand-edit|generated_utc|generated_at|"
    r"schema_version|source_head|source_base|exact_base_sha|baseline_sha|"
    r"^\"?(?:input_row|from|path|target)\"?,\"?(?:from|line|status|target))"
)
SNAPSHOT_NAME_RE = re.compile(
    r"(?i)(?:path_reference|changed_paths|snapshot|results?|receipts?|ledger|edges|dump|"
    r"manifest|清单|快照|结果|回执|账本)"
)
RUN_RECORD_NAME_RE = re.compile(
    r"(?i)(?:allowlist|receipt|结论|结果|记录|回传|清单|报告|派单|复核|审核|验收|"
    r"状态|模型|需求|答复|确认|决定|声明|说明)"
)


class ScanError(RuntimeError):
    """Fail-closed scanner error."""


def run_git(repo_root: Path, args: list[str], *, env: dict[str, str] | None = None) -> bytes:
    proc = subprocess.run(
        ["git", *args],
        cwd=repo_root,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip()
        raise ScanError(f"git {' '.join(args)} exited {proc.returncode}: {detail}")
    return proc.stdout


def resolve_commit(repo_root: Path, treeish: str) -> str:
    value = run_git(repo_root, ["rev-parse", f"{treeish}^{{commit}}"])
    commit = value.decode("ascii").strip()
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ScanError(f"treeish did not resolve to a 40-character commit: {treeish}")
    return commit


def tracked_paths(repo_root: Path, commit: str) -> list[str]:
    """Enumerate one immutable tree through the required git ls-files -z path."""
    with tempfile.TemporaryDirectory(prefix="os_namespace_index_") as temp_dir:
        index_path = Path(temp_dir) / "index"
        env = os.environ.copy()
        env["GIT_INDEX_FILE"] = str(index_path)
        run_git(repo_root, ["read-tree", commit], env=env)
        raw = run_git(repo_root, ["ls-files", "-z"], env=env)
    paths = [part.decode("utf-8", "surrogateescape") for part in raw.split(b"\0") if part]
    if paths != sorted(paths):
        paths.sort()
    return paths


def blob_bytes(repo_root: Path, commit: str, path: str) -> bytes:
    return run_git(repo_root, ["show", f"{commit}:{path}"])


def decode_tracked_text(data: bytes) -> tuple[str | None, str | None]:
    if b"\0" in data:
        return None, "binary_nul"
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return None, "non_utf8"
    control_count = sum(ord(char) < 32 and char not in "\n\r\t\f\b" for char in text)
    if text and control_count / len(text) > 0.01:
        return None, "binary_control_ratio"
    return text, None


def bounded(value: str, limit: int = 320) -> str:
    cleaned = value.rstrip("\r\n")
    if len(cleaned) <= limit:
        return cleaned
    return cleaned[: limit - 1] + "…"


def looks_like_bound_record(text: str) -> bool:
    return sum(marker in text for marker in BOUND_RECORD_MARKERS) >= 2


def classify_occurrence(path: str, line_text: str, context_text: str, document: str) -> dict[str, str]:
    """Conservative content-aware proposal; directory position is never sufficient."""
    normalized = path.replace("\\", "/")
    suffix = Path(normalized).suffix.lower()
    is_run_path = RUN_SEGMENT in normalized
    bound_record = looks_like_bound_record(document)
    historical_language = bool(HISTORICAL_FACT_RE.search(context_text))
    active_syntax = bool(ACTIVE_PATH_SYNTAX_RE.search(line_text))

    generated_evidence = bool(GENERATED_EVIDENCE_RE.search(document))
    named_data_snapshot = suffix in DATA_SNAPSHOT_SUFFIXES and bool(
        SNAPSHOT_NAME_RE.search(Path(normalized).name)
    )
    semantically_named_run_record = suffix not in CODE_SUFFIXES and bool(
        RUN_RECORD_NAME_RE.search(Path(normalized).name)
    )

    if is_run_path and suffix not in CODE_SUFFIXES and (generated_evidence or named_data_snapshot):
        return {
            "classification": "preserve_historical_literal",
            "rule": "generated_run_snapshot_or_receipt",
            "reason": (
                "File content/format identifies a generated snapshot, receipt, ledger, result, or path "
                "inventory from an earlier run. Its old path vocabulary is recorded evidence; _runs "
                "location alone was not used to reach this decision."
            ),
            "expected_after_cutover": "literal remains unchanged as the immutable observation produced by that run",
        }

    if is_run_path and semantically_named_run_record:
        return {
            "classification": "preserve_historical_literal",
            "rule": "semantically_named_run_record",
            "reason": (
                "The non-executable document is explicitly named as a task/run conclusion, result, record, "
                "handoff, manifest, review, decision, or model. That document semantic plus its recorded-run "
                "context identifies historical evidence; _runs location alone was not used."
            ),
            "expected_after_cutover": "literal remains unchanged as vocabulary recorded by that historical document",
        }

    if is_run_path and bound_record and suffix not in CODE_SUFFIXES:
        return {
            "classification": "preserve_historical_literal",
            "rule": "bound_run_record",
            "reason": (
                "The document carries multiple immutable task/run binding fields and this occurrence "
                "records that run's then-observed path vocabulary; the decision is based on record "
                "semantics, not on _runs location alone."
            ),
            "expected_after_cutover": "literal remains unchanged as historical evidence",
        }

    if historical_language and not active_syntax:
        return {
            "classification": "preserve_historical_literal",
            "rule": "explicit_historical_statement",
            "reason": "Bounded context explicitly describes a past state or retired-system fact.",
            "expected_after_cutover": "literal remains unchanged because rewriting would alter the recorded fact",
        }

    if is_run_path and suffix in CODE_SUFFIXES:
        return {
            "classification": "manual_review",
            "rule": "run_executable_ambiguous",
            "reason": (
                "This is executable run evidence. It may be frozen replay material or may still be invoked "
                "against the current tree; content and caller reachability require independent review."
            ),
            "expected_after_cutover": "review caller/replay contract before deciding whether to rewrite",
        }

    if not is_run_path and (active_syntax or suffix in CODE_SUFFIXES or ROOT_NAME in line_text):
        return {
            "classification": "rewrite_current_path",
            "rule": "current_tree_reference",
            "reason": (
                "The occurrence is in a current non-run artifact and is expressed as repository path, "
                "loader/manifest/registry/startup syntax, or executable path construction."
            ),
            "expected_after_cutover": "replace repository root segment 08_os with 01_os",
        }

    return {
        "classification": "manual_review",
        "rule": "insufficient_semantic_evidence",
        "reason": "Bounded content does not prove whether the literal is an active resolver or a historical fact.",
        "expected_after_cutover": "resolve during independent review before Checkpoint B",
    }


def scan(repo_root: Path, commit: str, context_lines: int) -> dict[str, Any]:
    paths = tracked_paths(repo_root, commit)
    physical_under_root = [path for path in paths if path.startswith(ROOT_NAME + "/")]
    entries: list[dict[str, Any]] = []
    text_file_count = 0
    skipped = Counter()

    for path in paths:
        raw = blob_bytes(repo_root, commit, path)
        text, reason = decode_tracked_text(raw)
        if text is None:
            skipped[reason or "unknown"] += 1
            continue
        text_file_count += 1
        lines = text.splitlines()
        for line_index, line_text in enumerate(lines):
            for occurrence_index, match in enumerate(REFERENCE_RE.finditer(line_text), start=1):
                matched_text = match.group(0).rstrip(".,;:")
                if not matched_text:
                    continue
                context_start = max(0, line_index - context_lines)
                context_end = min(len(lines), line_index + context_lines + 1)
                context = [
                    {"line": index + 1, "text": bounded(lines[index])}
                    for index in range(context_start, context_end)
                ]
                context_text = "\n".join(item["text"] for item in context)
                proposal = classify_occurrence(path, line_text, context_text, text)
                entries.append(
                    {
                        "path": path,
                        "line": line_index + 1,
                        "column": match.start() + 1,
                        "occurrence_on_line": occurrence_index,
                        "match": matched_text,
                        "line_text": bounded(line_text),
                        "context": context,
                        "proposed_classification": proposal["classification"],
                        "classification_rule": proposal["rule"],
                        "reason": proposal["reason"],
                        "expected_after_cutover": proposal["expected_after_cutover"],
                    }
                )

    entries.sort(key=lambda item: (item["path"], item["line"], item["column"]))
    file_hit_count = len({entry["path"] for entry in entries})
    classifications = Counter(entry["proposed_classification"] for entry in entries)
    return {
        "schema_version": "citystate.os_namespace_scan.v1",
        "source_commit": commit,
        "enumeration": "git ls-files -z with temporary index loaded from source_commit",
        "physical": {
            "tracked_total": len(paths),
            "tracked_under_08_os": len(physical_under_root),
        },
        "text": {
            "tracked_text_files_scanned": text_file_count,
            "files_with_08_os_reference": file_hit_count,
            "occurrences": len(entries),
            "skipped_non_text": dict(sorted(skipped.items())),
        },
        "classification": {
            "rewrite_current_path": classifications["rewrite_current_path"],
            "preserve_historical_literal": classifications["preserve_historical_literal"],
            "manual_review": classifications["manual_review"],
        },
        "entries": entries,
    }


def mapping_document(result: dict[str, Any]) -> dict[str, Any]:
    entries = []
    for item in result["entries"]:
        entries.append(
            {
                "path": item["path"],
                "line": item["line"],
                "column": item["column"],
                "old_text": item["match"],
                "classification": item["proposed_classification"],
                "classification_rule": item["classification_rule"],
                "reason": item["reason"],
                "expected_after_cutover": item["expected_after_cutover"],
            }
        )
    return {
        "schema_version": "citystate.os_namespace_mapping.v1",
        "task_id": "os-v2-01-os-namespace-and-autoload-cutover-001",
        "checkpoint": "A_inventory_and_mapping_freeze",
        "source_commit": result["source_commit"],
        "physical": {"tracked_under_08_os": result["physical"]["tracked_under_08_os"]},
        "text": {
            "files_with_08_os_reference": result["text"]["files_with_08_os_reference"],
            "occurrences": result["text"]["occurrences"],
        },
        "classification": result["classification"],
        "entries": entries,
    }


def write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=False) + "\n"
    path.write_text(payload, encoding="utf-8", newline="\n")


def write_yaml(path: Path, data: dict[str, Any]) -> None:
    if yaml is None:
        raise ScanError("PyYAML is required to write the mapping manifest")
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=120)
    path.write_text(payload, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--source-treeish", required=True)
    parser.add_argument("--output", required=True, help="complete JSON result path")
    parser.add_argument("--mapping-output", required=True, help="frozen YAML mapping path")
    parser.add_argument("--context-lines", type=int, default=1)
    args = parser.parse_args(argv)

    try:
        repo_root = Path(args.repo_root).resolve()
        commit = resolve_commit(repo_root, args.source_treeish)
        result = scan(repo_root, commit, max(0, min(args.context_lines, 3)))
        write_json(Path(args.output), result)
        write_yaml(Path(args.mapping_output), mapping_document(result))
        digest = hashlib.sha256(
            json.dumps(result, ensure_ascii=False, sort_keys=True).encode("utf-8")
        ).hexdigest()
    except (OSError, ScanError, ValueError) as exc:
        print(f"scan_error: {exc}", file=sys.stderr)
        return 2

    counts = result["classification"]
    print(
        "scan_ok "
        f"source={commit} "
        f"tracked_under_08_os={result['physical']['tracked_under_08_os']} "
        f"files_with_hit={result['text']['files_with_08_os_reference']} "
        f"occurrences={result['text']['occurrences']} "
        f"rewrite={counts['rewrite_current_path']} "
        f"historical={counts['preserve_historical_literal']} "
        f"manual={counts['manual_review']} "
        f"result_sha256={digest}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
