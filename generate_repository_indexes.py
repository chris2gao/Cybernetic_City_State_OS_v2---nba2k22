def deprecation_state(path: str) -> str | None:
    exact = DEPRECATION_EXACT_STATES.get(path)
    if exact:
        return exact
    for prefix, state in DEPRECATION_PREFIX_STATES:
        if path.startswith(prefix):
            return state
    if path.startswith(
        "08_Domain_Applications/Math_Mentor/Pure_Math_Intuition_DB/_Staging_"
    ):
        return "candidate_only"
    if (
        parent_directory(path)
        == "08_Domain_Applications/Math_Mentor/Pure_Math_Intuition_DB"
        and PurePosixPath(path).name.startswith("BRIDGE-")
        and PurePosixPath(path).suffix.casefold() == ".yaml"
    ):
        return "legacy_unresolved"
    return None


def index_path_for_directory(directory: str) -> str:
    return "index.md" if directory == "" else f"{directory}/index.md"


def parent_directory(path: str) -> str:
    parent = str(PurePosixPath(path).parent)
    return "" if parent == "." else parent


def derive_directories(entries: dict[str, GitEntry], blobs: dict[str, bytes]) -> list[str]:
    structural_paths: list[str] = []
    for path, entry in entries.items():
        if not path_is_index(path):
            structural_paths.append(path)
            continue
        data = blobs.get(entry.oid or "", b"")
        try:
            manual, has_markers = manual_bytes_and_marker_state(path, data)
        except IndexErrorDetail:
            raise
        if not has_markers or manual.strip():
            structural_paths.append(path)
    directories = {""}
    for path in structural_paths:
        current = parent_directory(path)
        while current:
            directories.add(current)
            current = parent_directory(current)
    return sorted(directories, key=unicode_sort_key)


def unicode_sort_key(value: str) -> tuple[int, ...]:
    return tuple(ord(ch) for ch in value)


def required_blob_oids(entries: dict[str, GitEntry]) -> set[str]:
    result: set[str] = set()
    for path, entry in entries.items():
        if entry.object_type != "blob" or not entry.oid:
            continue
        # Generated artifacts must remain readable when validating a committed
        # Git tree, including indexes located below metadata-only directories.
        if path_is_index(path) or path == MANIFEST_PATH:
            result.add(entry.oid)
            continue
        if path_is_private(path) or path in RESTRICTED_METADATA_ONLY:
            continue
        result.add(entry.oid)
    return result


def load_blobs(entries: dict[str, GitEntry]) -> dict[str, bytes]:
    oids = sorted(required_blob_oids(entries))
    if not oids:
        return {}
    payload = b"".join(oid.encode("ascii") + b"\n" for oid in oids)
    prefix, env = verified_git_context()
    process = subprocess.run(
        [*prefix, "cat-file", "--batch"],
        cwd=ROOT,
        input=payload,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
        check=False,
    )
    if process.returncode:
        raise IndexErrorDetail(process.stderr.decode("utf-8", "replace"))
    output = process.stdout
    cursor = 0
    blobs: dict[str, bytes] = {}
    for requested_oid in oids:
        line_end = output.find(b"\n", cursor)
        if line_end < 0:
            raise IndexErrorDetail("Truncated git cat-file batch header")
        header = output[cursor:line_end].decode("ascii")
        cursor = line_end + 1
        parts = header.split()
        if len(parts) != 3 or parts[1] != "blob":
            raise IndexErrorDetail(f"Unexpected git cat-file header: {header}")
        actual_oid, _, size_text = parts
        size = int(size_text)
        data = output[cursor : cursor + size]
        cursor += size
        if output[cursor : cursor + 1] != b"\n":
            raise IndexErrorDetail("Malformed git cat-file batch separator")
        cursor += 1
        if actual_oid != requested_oid:
            raise IndexErrorDetail("git cat-file returned an unexpected object")
        blobs[requested_oid] = data
    return blobs


def safe_text(value: Any, limit: int = 180) -> str:
    text = html.unescape(re.sub(r"\s+", " ", str(value)).strip())
    text = text[: max(512, limit * 4)]
    text = SENSITIVE_VALUE_RE.sub("[已移除敏感值]", text)
    text = (
        html.escape(text, quote=False)
        .replace("|", "&#124;")
        .replace("`", "&#96;")
        .replace("[", "［")
        .replace("]", "］")
    )
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def decode_utf8(path: str, data: bytes) -> tuple[str | None, str]:
    if data.startswith(b"\xff\xfe") or data.startswith(b"\xfe\xff"):
        return None, "non_utf8_bom_metadata_only"
    try:
        return data.decode("utf-8-sig", "strict"), "utf8"
    except UnicodeDecodeError:
        return None, "non_utf8_metadata_only"


def extract_markdown(path: str, text: str) -> dict[str, Any]:
    headings = []
    for line in text.splitlines():
        match = re.match(r"^\s{0,3}(#{1,6})\s+(.+?)\s*$", line)
        if match:
            headings.append((len(match.group(1)), safe_text(match.group(2), 120)))
    title = next((value for level, value in headings if level == 1), None)
    section = next((value for level, value in headings if level == 2), None)
    first_line = next(
        (
            safe_text(line, 120)
            for line in text.splitlines()
            if line.strip()
            and not line.lstrip().startswith(("#", "---", "<!--", "```", ">"))
        ),
        None,
    )
    anchors = []
    if title:
        anchors.append(f"H1《{title}》")
    if section:
        anchors.append(f"首个 H2《{section}》")
    if not anchors and first_line:
        anchors.append(f"首行“{first_line}”")
    if not anchors:
        anchors.append(f"Markdown {len(text.splitlines())} 行，无可用标题")
    return {
        "summary": "；".join(anchors),
        "description_basis": "markdown_heading_or_visible_structure",
        "anchors": anchors,
        "encoding": "utf8",
    }


