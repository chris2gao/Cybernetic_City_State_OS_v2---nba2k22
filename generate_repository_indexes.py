    safe_patterns = [safe_text(pattern, 40) for pattern in patterns[:6]]
    return {
        "summary": f"Git ignore 规则 {len(patterns)} 条；样例：{', '.join(safe_patterns)}",
        "description_basis": "gitignore_pattern_count_and_safe_samples",
        "anchors": [f"patterns={len(patterns)}", *safe_patterns],
        "encoding": "utf8",
    }


