def check_outputs(ref: str | None) -> dict[str, Any]:
    expected, manifest = build_expected(ref)
    entries = load_git_entries(ref)
    blobs = load_blobs(entries)
    mismatches = []
    for path, expected_bytes in expected.items():
        actual = read_output(path, ref, entries, blobs)
        if actual != expected_bytes:
            mismatches.append(path)
    if mismatches:
        raise IndexErrorDetail(f"Deterministic check differs: {mismatches[:20]}")
    return {
        "status": "pass",
        "ref": ref or "git-index-and-worktree",
        "checked_outputs": len(expected),
        "hashes": manifest["hashes"],
    }


def snapshot(ref: str | None) -> dict[str, Any]:
    outputs, manifest = build_expected(ref)
    bundle_hash = sha256_records(
        path.encode("utf-8") + b"\0" + outputs[path] + b"\0"
        for path in sorted(outputs, key=unicode_sort_key)
    )
    return {
        "schema_version": SCHEMA_VERSION,
        "ref": ref or "git-index",
        "output_count": len(outputs),
        "output_bundle_sha256": bundle_hash,
        "manifest_sha256": hashlib.sha256(outputs[MANIFEST_PATH]).hexdigest(),
        "hashes": manifest["hashes"],
    }


def compare_semantic_baseline(ref: str) -> dict[str, Any]:
    baseline_entries = load_git_entries(ref)
    baseline_blobs = load_blobs(baseline_entries)
    manifest_entry = baseline_entries.get(MANIFEST_PATH)
    if not manifest_entry or not manifest_entry.oid:
        raise IndexErrorDetail(f"Baseline manifest is missing at {ref}")
    baseline_manifest = json.loads(
        baseline_blobs[manifest_entry.oid].decode("utf-8", "strict")
    )
    _, current_manifest = build_expected(None)

    def file_map(manifest: dict[str, Any]) -> dict[str, dict[str, Any]]:
        return {
            item["path"]: item
            for directory in manifest["directories"]
            for item in directory["direct_files"]
        }

    def child_map(manifest: dict[str, Any]) -> dict[str, dict[str, Any]]:
        return {
            item["path"]: item
            for directory in manifest["directories"]
            for item in directory["child_directories"]
        }

    baseline_files = file_map(baseline_manifest)
    current_files = file_map(current_manifest)
    baseline_children = child_map(baseline_manifest)
    current_children = child_map(current_manifest)
    baseline_directories = {
        item["path"]: item for item in baseline_manifest["directories"]
    }
    current_directories = {
        item["path"]: item for item in current_manifest["directories"]
    }
    if set(baseline_files) - set(current_files):
        raise IndexErrorDetail("A baseline file disappeared from the semantic audit")
    if set(baseline_children) != set(current_children):
        raise IndexErrorDetail("Baseline/current child-directory sets differ")
    if set(baseline_directories) != set(current_directories):
        raise IndexErrorDetail("Baseline/current directory sets differ")

    fields = (
        "content_summary",
        "role_and_use",
        "authority_class",
        "status_or_freshness",
        "when_to_read",
    )
    changed_by_field = {
        field: sum(
            baseline_files[path].get(field) != current_files[path].get(field)
            for path in baseline_files
        )
        for field in fields
    }
    corrected = sum(
        any(
            baseline_files[path].get(field) != current_files[path].get(field)
            for field in fields
        )
        for path in baseline_files
    )
    baseline_semantic_fields = ("role_and_use", "status_or_freshness", "when_to_read")
    repeated_counts = {
        field: Counter(item[field] for item in baseline_files.values())
        for field in baseline_semantic_fields
    }
    repeated_semantic_entries = sum(
        any(repeated_counts[field][item[field]] > 1 for field in baseline_semantic_fields)
        for item in baseline_files.values()
    )
    result = {
        "status": "pass",
        "baseline_ref": ref,
        "baseline_files": len(baseline_files),
        "current_files": len(current_files),
        "baseline_files_present_exactly_once": len(set(baseline_files) & set(current_files)),
        "file_entries_corrected": corrected,
        "file_entries_passed_without_change": len(baseline_files) - corrected,
        "changed_by_field": changed_by_field,
        "directory_roles_corrected": sum(
            baseline_directories[path]["directory_role"]
            != current_directories[path]["directory_role"]
            for path in baseline_directories
        ),
        "child_directory_roles_corrected": sum(
            baseline_children[path]["content_scope"]
            != current_children[path]["content_scope"]
            for path in baseline_children
        ),
        "child_directory_triggers_corrected": sum(
            baseline_children[path]["when_to_enter"]
            != current_children[path]["when_to_enter"]
            for path in baseline_children
        ),
        "baseline_entries_with_repeated_semantic_text": repeated_semantic_entries,
    }
    expected = current_manifest["semantic_audit"]["baseline_correction_summary"]
    checks = {
        "file_entries_corrected": result["file_entries_corrected"],
        "file_entries_passed_without_change": result[
            "file_entries_passed_without_change"
        ],
        "directory_roles_corrected": result["directory_roles_corrected"],
        "child_directory_roles_or_triggers_corrected": max(
            result["child_directory_roles_corrected"],
            result["child_directory_triggers_corrected"],
        ),
        "authority_classes_corrected": changed_by_field["authority_class"],
        "freshness_labels_corrected": changed_by_field["status_or_freshness"],
        "read_triggers_corrected": changed_by_field["when_to_read"],
        "baseline_entries_with_repeated_semantic_text_removed": repeated_semantic_entries,
    }
    for key, value in checks.items():
        if expected[key] != value:
            raise IndexErrorDetail(
                f"Baseline semantic accounting differs for {key}: "
                f"expected={expected[key]} actual={value}"
            )
    return result


