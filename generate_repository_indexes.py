def render_recommended_order(
    directory: str,
    record: dict[str, Any],
    all_file_records: dict[str, dict[str, Any]],
) -> list[str]:
    lines = []
    file_by_path = {item["path"]: item for item in record["direct_files"]}
    child_by_index = {
        index_path_for_directory(item["path"]): item for item in record["child_directories"]
    }
    if directory == "":
        number = 1
        for path in ROOT_READING_ORDER:
            item = all_file_records.get(path)
            child = child_by_index.get(path)
            if item:
                reason = item["when_to_read"]
            elif child:
                reason = child["when_to_enter"]
            else:
                continue
            lines.append(
                f"{number}. [`{markdown_escape_text(path)}`]({link_for(directory, path)}) — {reason}"
            )
            number += 1
            if path == "06_Silicon_Index/AI_Bootstrap_Sequence.md":
                lines.append(
                    f"{number}. 当前 Human 指令；若属于 handoff，再物理读取 `ai/review/latest` 活动 mailbox — 它们不是 master 静态快照；先据此决定后续最小合同集合。"
                )
                number += 1
        return lines
    if directory in DIRECTORY_READING_ORDERS:
        for number, path in enumerate(DIRECTORY_READING_ORDERS[directory], 1):
            item = all_file_records.get(path)
            if item is None or parent_directory(path) != directory:
                raise IndexErrorDetail(
                    f"Curated reading-order path is missing or non-direct: {directory} -> {path}"
                )
            lines.append(
                f"{number}. [`{markdown_escape_text(path)}`]({link_for(directory, path)}) — {item['when_to_read']}"
            )
        return lines
    ordered_files = sorted(record["direct_files"], key=priority_for_file)
    number = 1
    for item in ordered_files[:6]:
        path = item["path"]
        lines.append(
            f"{number}. [`{markdown_escape_text(path)}`]({link_for(directory, path)}) — {item['when_to_read']}"
        )
        number += 1
    for child in record["child_directories"][:3]:
        path = index_path_for_directory(child["path"])
        lines.append(
            f"{number}. [`{markdown_escape_text(path)}`]({link_for(directory, path)}) — {child['when_to_enter']}"
        )
        number += 1
    return lines or ["1. 本目录仅有索引自身；先核验 Git tree 再决定是否继续。"]


