def extract_file_metadata(entry: GitEntry, data: bytes | None) -> dict[str, Any]:
    path = entry.path
    if path_is_index(path):
        return {
            "content_summary": "本目录的确定性懒加载路由索引；生成块覆盖 direct files 与 child directories",
            "description_basis": "synthetic_index_self_entry",
            "anchors": ["repository_index_self"],
            "encoding": "utf8_generated",
            "byte_size": None,
        }
    if path == MANIFEST_PATH:
        return {
            "content_summary": "repository_index_manifest.v1 机器覆盖清单；双向映射目录、直接文件与直接子目录",
            "description_basis": "synthetic_manifest_self_entry",
            "anchors": [SCHEMA_VERSION],
            "encoding": "utf8_json_generated",
            "byte_size": None,
        }
    if entry.object_type != "blob":
        return {
            "content_summary": f"Git {entry.object_type} 对象，mode={entry.mode}；索引不跟随目标",
            "description_basis": "git_object_mode_metadata_only",
            "anchors": [f"mode={entry.mode}", f"type={entry.object_type}"],
            "encoding": "not_read_special_object",
            "byte_size": None,
        }
    if path_is_private(path):
        return {
            "content_summary": f"Private Zones tracked artifact；mode={entry.mode}，仅记录路径/格式边界，正文未读取",
            "description_basis": "restricted_private_metadata_only",
            "anchors": ["private_zone", f"suffix={PurePosixPath(path).suffix or 'none'}"],
            "encoding": "not_read_private_boundary",
            "byte_size": None,
        }
    if path in RESTRICTED_METADATA_ONLY:
        return {
            "content_summary": "受 AGENTS 读取限制的完整数学路线图 YAML；仅确认 tracked 路径/格式，优先使用分级路线图",
            "description_basis": "restricted_roadmap_metadata_only",
            "anchors": ["restricted_full_roadmap", "yaml"],
            "encoding": "not_read_repository_rule",
            "byte_size": None,
        }
    if data is None:
        raise IndexErrorDetail(f"Missing blob bytes for {path}")
    if path in SPECIAL_SUMMARIES:
        summary, basis = SPECIAL_SUMMARIES[path]
        return {
            "content_summary": summary,
            "description_basis": basis,
            "anchors": [summary],
            "encoding": "utf8_curated",
            "byte_size": None if path in SELF_REFERENTIAL_METADATA_PATHS else len(data),
        }
    suffix = PurePosixPath(path).suffix.lower()
    if suffix == ".docx":
        result = extract_docx(path, data)
    elif suffix == ".xml":
        result = extract_xml(path, data)
    else:
        text, encoding = decode_utf8(path, data)
        if text is None:
            result = {
                "summary": f"非 UTF-8 tracked blob；mode={entry.mode}，仅记录格式边界，正文未转码",
                "description_basis": "non_utf8_metadata_only",
                "anchors": [encoding, f"suffix={suffix or 'none'}"],
                "encoding": encoding,
            }
        elif path == ".gitignore":
            result = extract_gitignore(text)
        elif suffix == ".md":
            result = extract_markdown(path, text)
        elif suffix == ".json":
            result = extract_json(path, text)
        elif suffix == ".jsonl":
            result = extract_jsonl(path, text)
        elif suffix in {".yaml", ".yml"}:
            result = extract_yaml(path, text)
        elif suffix == ".py":
            result = extract_python(path, text)
        elif suffix in {".log", ".txt", ".bat"} or not suffix:
            result = extract_log_or_text(path, text)
        else:
            result = extract_log_or_text(path, text)
    result = dict(result)
    result["content_summary"] = result.pop("summary")
    result["byte_size"] = None if path in SELF_REFERENTIAL_METADATA_PATHS else len(data)
    return result


