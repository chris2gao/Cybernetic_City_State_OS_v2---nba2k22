class IndexErrorDetail(RuntimeError):
    """Fail-closed index generation or validation error."""


@dataclass(frozen=True)
class GitEntry:
    path: str
    mode: str
    oid: str | None
    object_type: str
    synthetic: bool = False


def sanitized_git_environment() -> dict[str, str]:
    # Local inventory must not inherit repository-selection or config overrides
    # such as GIT_INDEX_FILE from a caller-controlled environment.
    env = {
        key: value
        for key, value in os.environ.items()
        if not key.upper().startswith("GIT_")
    }
    env["LC_ALL"] = "C"
    env["LANG"] = "C"
    return env


def verified_git_context() -> tuple[list[str], dict[str, str]]:
    env = sanitized_git_environment()
    prefix = ["git", "-C", str(ROOT)]
    top = subprocess.run(
        [*prefix, "rev-parse", "--show-toplevel"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
        check=False,
    )
    if top.returncode:
        raise IndexErrorDetail("Git repository root could not be verified")
    try:
        reported_root = Path(top.stdout.decode("utf-8", "strict").strip()).resolve()
    except (UnicodeDecodeError, OSError) as exc:
        raise IndexErrorDetail("Git reported an invalid repository root") from exc
    if reported_root != ROOT.resolve():
        raise IndexErrorDetail(
            f"Git repository root mismatch: expected={ROOT.resolve()} actual={reported_root}"
        )
    return prefix, env


def run_git(args: list[str], *, input_bytes: bytes | None = None) -> bytes:
    prefix, env = verified_git_context()
    process = subprocess.run(
        [*prefix, *args],
        cwd=ROOT,
        input=input_bytes,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
        check=False,
    )
    if process.returncode:
        message = process.stderr.decode("utf-8", "replace").strip()
        raise IndexErrorDetail(f"git {' '.join(args)} failed: {message}")
    return process.stdout


def decode_git_path(raw: bytes) -> str:
    try:
        path = raw.decode("utf-8", "strict")
    except UnicodeDecodeError as exc:
        raise IndexErrorDetail(f"Git path is not UTF-8: {exc}") from exc
    raw_parts = path.split("/")
    parts = PurePosixPath(path).parts
    windows_reserved = re.compile(r"^(?:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\..*)?$", re.I)
    if (
        not path
        or "\\" in path
        or path.startswith("/")
        or "\x00" in path
        or any(part in {"", ".", ".."} for part in raw_parts)
        or any(ord(char) < 0x20 or ord(char) == 0x7F for char in path)
        or any(char in path for char in ':*?"<>|`')
        or any(part.endswith((" ", ".")) for part in parts)
        or any(windows_reserved.match(part) for part in parts)
    ):
        raise IndexErrorDetail(f"Unsafe Git path: {path!r}")
    if unicodedata.normalize("NFC", path) != path:
        raise IndexErrorDetail(f"Non-NFC Git path is unsupported: {path!r}")
    return path


def load_git_entries(ref: str | None) -> dict[str, GitEntry]:
    entries: dict[str, GitEntry] = {}
    if ref is None:
        raw = run_git(["ls-files", "--stage", "-z"])
        for record in raw.split(b"\0"):
            if not record:
                continue
            meta, raw_path = record.split(b"\t", 1)
            mode_b, oid_b, stage_b = meta.split(b" ", 2)
            if stage_b != b"0":
                raise IndexErrorDetail(
                    f"Unmerged Git index entry: {decode_git_path(raw_path)} stage={stage_b!r}"
                )
            path = decode_git_path(raw_path)
            if path in entries:
                raise IndexErrorDetail(f"Duplicate Git path detected: {path}")
            mode = mode_b.decode("ascii")
            oid = oid_b.decode("ascii")
            object_type = object_type_for_mode(mode)
            entries[path] = GitEntry(path, mode, oid, object_type)
    else:
        raw = run_git(["ls-tree", "-r", "-z", "--full-tree", ref])
        for record in raw.split(b"\0"):
            if not record:
                continue
            meta, raw_path = record.split(b"\t", 1)
            mode_b, type_b, oid_b = meta.split(b" ", 2)
            path = decode_git_path(raw_path)
            if path in entries:
                raise IndexErrorDetail(f"Duplicate Git path detected: {path}")
            mode = mode_b.decode("ascii")
            oid = oid_b.decode("ascii")
            git_type = type_b.decode("ascii")
            expected_git_type = "commit" if mode == "160000" else "blob"
            if git_type != expected_git_type:
                raise IndexErrorDetail(
                    f"Inconsistent ls-tree mode/type for {path}: mode={mode} type={git_type}"
                )
            object_type = object_type_for_mode(mode)
            entries[path] = GitEntry(path, mode, oid, object_type)
    return entries


def object_type_for_mode(mode: str) -> str:
    if mode == "120000":
        return "symlink"
    if mode == "160000":
        return "commit"
    if mode.startswith("100"):
        return "blob"
    return "special"


