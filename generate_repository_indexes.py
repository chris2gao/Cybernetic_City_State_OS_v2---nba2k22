def make_final_entries(
    entries: dict[str, GitEntry], directories: list[str]
) -> dict[str, GitEntry]:
    result = dict(entries)
    casefold_paths = {path.casefold(): path for path in entries}
    if len(casefold_paths) != len(entries):
        raise IndexErrorDetail("Case-insensitive tracked path collision detected")
    for directory in directories:
        path = index_path_for_directory(directory)
        existing_case = casefold_paths.get(path.casefold())
        if existing_case and existing_case != path:
            raise IndexErrorDetail(f"index.md case collision: {existing_case} vs {path}")
        if path not in result:
            result[path] = GitEntry(path, "100644", None, "blob", synthetic=True)
    return result


def posix_direct_children(
    directories: list[str], final_entries: dict[str, GitEntry]
) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    files_by_parent: dict[str, list[str]] = defaultdict(list)
    children_by_parent: dict[str, list[str]] = defaultdict(list)
    directory_set = set(directories)
    for path in final_entries:
        parent = parent_directory(path)
        if parent not in directory_set:
            raise IndexErrorDetail(f"Tracked file has missing directory: {path} -> {parent}")
        files_by_parent[parent].append(path)
    for directory in directories:
        if not directory:
            continue
        parent = parent_directory(directory)
        if parent not in directory_set:
            raise IndexErrorDetail(f"Directory has missing parent: {directory}")
        children_by_parent[parent].append(directory)
    for mapping in (files_by_parent, children_by_parent):
        for key in mapping:
            mapping[key].sort(key=unicode_sort_key)
    return files_by_parent, children_by_parent


def build_records(
    entries: dict[str, GitEntry], blobs: dict[str, bytes]
) -> tuple[list[str], dict[str, GitEntry], dict[str, dict[str, Any]], list[dict[str, Any]]]:
    directories = derive_directories(entries, blobs)
    final_entries = make_final_entries(entries, directories)
    file_records: dict[str, dict[str, Any]] = {}
    for path in sorted(final_entries, key=unicode_sort_key):
        entry = final_entries[path]
        data = blobs.get(entry.oid or "")
        file_records[path] = file_record(entry, data)
    duplicate_summaries: dict[str, list[str]] = defaultdict(list)
    for path, record in file_records.items():
        if not path_is_index(path):
            duplicate_summaries[record["content_summary"]].append(path)
    for summary, paths in duplicate_summaries.items():
        if len(paths) <= 1:
            continue
        for path in paths:
            file_records[path]["content_summary"] = safe_text(
                f"{summary}；artifact={PurePosixPath(path).name}"
            )
    files_by_parent, children_by_parent = posix_direct_children(directories, final_entries)
    all_paths = sorted(final_entries, key=unicode_sort_key)
    directory_records: list[dict[str, Any]] = []
    for directory in directories:
        descendants = directory_descendant_paths(directory, all_paths)
        role = directory_role(directory, descendants)
        child_records = []
        for child in children_by_parent.get(directory, []):
            child_descendants = directory_descendant_paths(child, all_paths)
            child_records.append(
                child_directory_record(
                    child, directory_role(child, child_descendants), len(child_descendants)
                )
            )
        directory_records.append(
            {
                "path": directory,
                "index_path": index_path_for_directory(directory),
                "directory_role": role,
                "semantic_profile": directory_semantic_profile(directory),
                "semantic_audit_status": "reviewed",
                "child_directories": child_records,
                "direct_files": [file_records[path] for path in files_by_parent[directory]],
            }
        )
    return directories, final_entries, file_records, directory_records


def hex_path(path: str) -> str:
    return path.encode("utf-8").hex()


def markdown_link_target(path: str) -> str:
    encoded = []
    unsafe = set(" #%?()[]<>\\")
    for char in path:
        if char in unsafe or ord(char) < 0x20 or ord(char) == 0x7F:
            encoded.extend(f"%{byte:02X}" for byte in char.encode("utf-8"))
        else:
            encoded.append(char)
    return "".join(encoded)


def link_for(index_directory: str, target_path: str) -> str:
    base = index_directory or "."
    relative = posixpath.relpath(target_path, base)
    if relative.startswith("../") or relative == "..":
        raise IndexErrorDetail(
            f"Generated index attempted a non-direct upward link: {index_directory} -> {target_path}"
        )
    return markdown_link_target(relative)


def markdown_escape_text(value: str) -> str:
    return value.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


