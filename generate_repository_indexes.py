def marker_inside_literal_context(data: bytes, marker_offset: int) -> bool:
    prefix = data[:marker_offset].decode("utf-8", "strict")
    fence: str | None = None
    for line in prefix.splitlines():
        stripped = line.lstrip()
        if stripped.startswith("```"):
            fence = None if fence == "```" else ("```" if fence is None else fence)
        elif stripped.startswith("~~~"):
            fence = None if fence == "~~~" else ("~~~" if fence is None else fence)
    if fence is not None:
        return True
    lower = prefix.casefold()
    for tag in ("pre", "code", "script", "style"):
        if lower.rfind(f"<{tag}") > lower.rfind(f"</{tag}>"):
            return True
    return lower.rfind("<!--") > lower.rfind("-->")


def marker_line_span(data: bytes, marker: bytes) -> tuple[int, int] | None:
    pattern = re.compile(rb"(?m)^" + re.escape(marker) + rb"(?=\r?$)")
    matches = list(pattern.finditer(data))
    if not matches:
        return None
    if len(matches) != 1:
        raise IndexErrorDetail(f"Ambiguous exact-line marker: {marker!r}")
    match = matches[0]
    return match.start(), match.end()


def manual_bytes_and_marker_state(path: str, data: bytes) -> tuple[bytes, bool]:
    try:
        data.decode("utf-8", "strict")
    except UnicodeDecodeError as exc:
        raise IndexErrorDetail(f"Existing index is not UTF-8: {path}") from exc
    start = START_MARKER.encode("ascii")
    end = END_MARKER.encode("ascii")
    start_count = data.count(start)
    end_count = data.count(end)
    if start_count == 0 and end_count == 0:
        return data, False
    if start_count != 1 or end_count != 1:
        raise IndexErrorDetail(
            f"Ambiguous generated markers in {path}: start={start_count}, end={end_count}"
        )
    start_span = marker_line_span(data, start)
    end_span = marker_line_span(data, end)
    if start_span is None or end_span is None:
        raise IndexErrorDetail(f"Generated marker is not an exact standalone line: {path}")
    start_at, _ = start_span
    end_at, end_after = end_span
    if end_at < start_at:
        raise IndexErrorDetail(f"Generated markers out of order in {path}")
    if marker_inside_literal_context(data, start_at) or marker_inside_literal_context(
        data, end_at
    ):
        raise IndexErrorDetail(f"Generated marker appears inside a literal context: {path}")
    prefix = data[:start_at]
    suffix = data[end_after:]
    return prefix + suffix, True


def generated_block_bytes(path: str, data: bytes) -> bytes:
    _, has_markers = manual_bytes_and_marker_state(path, data)
    if not has_markers:
        raise IndexErrorDetail(f"Generated index lacks control markers: {path}")
    start_span = marker_line_span(data, START_MARKER.encode("ascii"))
    end_span = marker_line_span(data, END_MARKER.encode("ascii"))
    assert start_span is not None and end_span is not None
    return data[start_span[0] : end_span[1]]


def merge_generated_block(path: str, existing: bytes | None, block: str) -> tuple[bytes, bytes]:
    start = START_MARKER.encode("ascii")
    end = END_MARKER.encode("ascii")
    generated = block.encode("utf-8")
    if existing is None:
        return start + b"\n" + generated + end + b"\n", b""
    manual, has_markers = manual_bytes_and_marker_state(path, existing)
    if has_markers:
        start_span = marker_line_span(existing, start)
        end_span = marker_line_span(existing, end)
        assert start_span is not None and end_span is not None
        start_at, _ = start_span
        _, end_after = end_span
        prefix = existing[:start_at]
        suffix = existing[end_after:]
        return prefix + start + b"\n" + generated + end + suffix, manual
    separator = b"" if not existing or existing.endswith((b"\n", b"\r")) else b"\n"
    return existing + separator + start + b"\n" + generated + end + b"\n", manual


def sha256_records(records: Iterable[bytes]) -> str:
    digest = hashlib.sha256()
    for record in records:
        digest.update(record)
    return digest.hexdigest()


def canonical_json_bytes(value: Any) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2, separators=(",", ": "))
        + "\n"
    ).encode("utf-8")


def filesystem_entry_is_reparse_point(value: os.stat_result) -> bool:
    flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0)
    return bool(getattr(value, "st_file_attributes", 0) & flag)


def safe_output_target(
    path: str, *, create_parents: bool = True, root: Path | None = None
) -> Path:
    """Return a repository-contained regular output path without following links."""

    pure = PurePosixPath(path)
    repository_root = (root or ROOT).resolve(strict=True)
    if pure.is_absolute() or any(
        part in {"", ".", ".."} for part in path.split("/")
    ):
        raise IndexErrorDetail(f"Unsafe output path: {path!r}")
    current = repository_root
    for part in pure.parts[:-1]:
        candidate = current / part
        if os.path.lexists(candidate):
            value = os.lstat(candidate)
            if not stat.S_ISDIR(value.st_mode) or filesystem_entry_is_reparse_point(value):
                raise IndexErrorDetail(
                    f"Output parent is not a plain directory: {candidate}"
                )
        else:
            if not create_parents:
                return repository_root.joinpath(*pure.parts)
            candidate.mkdir()
            value = os.lstat(candidate)
            if not stat.S_ISDIR(value.st_mode) or filesystem_entry_is_reparse_point(value):
                raise IndexErrorDetail(
                    f"Created output parent is not a plain directory: {candidate}"
                )
        current = candidate
    try:
        current.resolve(strict=True).relative_to(repository_root)
    except (OSError, ValueError) as exc:
        raise IndexErrorDetail(f"Output parent escapes repository: {current}") from exc
    target = current / pure.name
    if os.path.lexists(target):
        value = os.lstat(target)
        if (
            not stat.S_ISREG(value.st_mode)
            or filesystem_entry_is_reparse_point(value)
            or value.st_nlink != 1
        ):
            raise IndexErrorDetail(f"Output target is not a plain regular file: {target}")
    return target


def build_expected(ref: str | None) -> tuple[dict[str, bytes], dict[str, Any]]:
    entries = load_git_entries(ref)
    blobs = load_blobs(entries)
    directories, final_entries, file_records, directory_records = build_records(entries, blobs)
    record_by_directory = {record["path"]: record for record in directory_records}
    for output_path in [
        *(index_path_for_directory(directory) for directory in directories),
        MANIFEST_PATH,
    ]:
        existing_output = entries.get(output_path)
        if existing_output and existing_output.object_type != "blob":
            raise IndexErrorDetail(
                f"Generated output path is a non-blob Git object: {output_path} "
                f"({existing_output.object_type})"
            )
    index_outputs: dict[str, bytes] = {}
    manual_hashes: dict[str, str] = {}
    for directory in directories:
        index_path = index_path_for_directory(directory)
        existing_entry = entries.get(index_path)
        existing = blobs.get(existing_entry.oid or "") if existing_entry else None
        rendered, manual = merge_generated_block(
            index_path,
            existing,
            render_generated_block(
                directory, record_by_directory[directory], file_records
            ),
        )
        index_outputs[index_path] = rendered
        if manual.strip():
            manual_hashes[index_path] = hashlib.sha256(manual).hexdigest()
    files_by_parent, children_by_parent = posix_direct_children(directories, final_entries)
    pathset_hash = sha256_records(
        path.encode("utf-8") + b"\0" for path in sorted(final_entries, key=unicode_sort_key)
    )
    directory_hash = sha256_records(
        directory.encode("utf-8") + b"\0" for directory in directories
    )
    edges: list[bytes] = []
    for directory in directories:
        for child in children_by_parent.get(directory, []):
            edges.append(f"D\0{directory}\0{child}\n".encode("utf-8"))
        for path in files_by_parent.get(directory, []):
            edges.append(f"F\0{directory}\0{path}\n".encode("utf-8"))
    coverage_hash = sha256_records(edges)
    output_hash = sha256_records(
        path.encode("utf-8") + b"\0" + index_outputs[path] + b"\0"
        for path in sorted(index_outputs, key=unicode_sort_key)
    )
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "task_id": TASK_ID,
        "source_baseline": SOURCE_BASELINE,
        "generator_path": GENERATOR_PATH,
        "inventory_source": "NUL-delimited tracked Git tree (ls-files/ls-tree)",
        "root_directory_encoding": "empty_string",
        "ordering_rule": "raw Unicode code point order; repository-relative POSIX paths",
        "generated_markers": {"start": START_MARKER, "end": END_MARKER},
        "counts": {
            "tracked_directories": len(directories),
            "index_files": len(index_outputs),
            "tracked_files_final": len(final_entries),
            "direct_file_edges": sum(len(value) for value in files_by_parent.values()),
            "direct_child_directory_edges": sum(
                len(value) for value in children_by_parent.values()
            ),
            "manual_index_sections": len(manual_hashes),
            "symlinks": sum(entry.object_type == "symlink" for entry in final_entries.values()),
            "submodules": sum(entry.object_type == "commit" for entry in final_entries.values()),
        },
        "hashes": {
            "tracked_pathset_sha256": pathset_hash,
            "directory_set_sha256": directory_hash,
            "coverage_edges_sha256": coverage_hash,
            "generated_indexes_sha256": output_hash,
        },
        "manual_index_preservation": {
            "paths": [
                {"path": path, "outside_markers_sha256": manual_hashes[path]}
                for path in sorted(manual_hashes, key=unicode_sort_key)
            ]
        },
        "directories": directory_records,
    }
    outputs = dict(index_outputs)
    outputs[MANIFEST_PATH] = canonical_json_bytes(manifest)
    return outputs, manifest


def write_outputs(outputs: dict[str, bytes]) -> list[str]:
    changed: list[str] = []
    for path in sorted(outputs, key=unicode_sort_key):
        target = safe_output_target(path)
        current = target.read_bytes() if target.exists() else None
        if current != outputs[path]:
            target.write_bytes(outputs[path])
            changed.append(path)
    return changed


def read_output(path: str, ref: str | None, entries: dict[str, GitEntry], blobs: dict[str, bytes]) -> bytes | None:
    if ref is None:
        target = safe_output_target(path, create_parents=False)
        return target.read_bytes() if os.path.lexists(target) else None
    entry = entries.get(path)
    if not entry or not entry.oid:
        return None
    return blobs.get(entry.oid)


def extract_machine_paths(data: bytes, marker: str) -> list[str]:
    text = data.decode("utf-8", "strict")
    pattern = re.compile(rf"<!-- {re.escape(marker)} ([0-9a-f]+) -->")
    paths = []
    for encoded in pattern.findall(text):
        try:
            paths.append(bytes.fromhex(encoded).decode("utf-8", "strict"))
        except (ValueError, UnicodeDecodeError) as exc:
            raise IndexErrorDetail(f"Invalid {marker} path encoding") from exc
    return paths


def validate_outputs(ref: str | None) -> dict[str, Any]:
    expected, expected_manifest = build_expected(ref)
    entries = load_git_entries(ref)
    blobs = load_blobs(entries)
    expected_paths = set(expected)
    actual_index_paths = {path for path in entries if path_is_index(path)}
    expected_index_paths = expected_paths - {MANIFEST_PATH}
    if actual_index_paths != expected_index_paths:
        raise IndexErrorDetail(
            f"Index path mismatch: missing={sorted(expected_index_paths-actual_index_paths)} "
            f"orphan={sorted(actual_index_paths-expected_index_paths)}"
        )
    if MANIFEST_PATH not in entries:
        raise IndexErrorDetail("Manifest is not tracked in the selected Git inventory")
    mismatches = []
    for path, expected_bytes in expected.items():
        actual = read_output(path, ref, entries, blobs)
        if actual != expected_bytes:
            mismatches.append(path)
    if mismatches:
        raise IndexErrorDetail(f"Generated outputs differ: {mismatches[:20]}")
    manifest_bytes = read_output(MANIFEST_PATH, ref, entries, blobs)
    assert manifest_bytes is not None
    manifest = json.loads(manifest_bytes.decode("utf-8", "strict"))
    if manifest != expected_manifest:
        raise IndexErrorDetail("Manifest semantic value differs from deterministic expectation")
    directory_records = {record["path"]: record for record in manifest["directories"]}
    all_file_paths = set(entries)
    all_directory_paths = set(directory_records)
    file_coverage: Counter[str] = Counter()
    child_coverage: Counter[str] = Counter()
    secret_findings = 0
    generic_findings = []
    markdown_failures = []
    unsafe_links = []
    broken_links = []
    for directory, record in directory_records.items():
        index_path = record["index_path"]
        data = read_output(index_path, ref, entries, blobs)
        assert data is not None
        data.decode("utf-8", "strict")
        generated = generated_block_bytes(index_path, data)
        text = generated.decode("utf-8", "strict")
        if (
            generated.startswith(b"\xef\xbb\xbf")
            or b"\r\n" in generated
            or b"\x00" in data
        ):
            raise IndexErrorDetail(f"Generated index is not canonical UTF-8 LF: {index_path}")
        if text.count(START_MARKER) != 1 or text.count(END_MARKER) != 1:
            markdown_failures.append(f"marker:{index_path}")
        without_control_comments = re.sub(
            r"<!-- (?:REPOSITORY_INDEX_AUTOGENERATED_(?:START|END)|RIDX_(?:FILE|DIR)_HEX [0-9a-f]+) -->",
            "",
            text,
        )
        if re.search(r"</?[A-Za-z!][^>]*>", without_control_comments):
            markdown_failures.append(f"raw-html:{index_path}")
        positions = [text.find(f"## {section}") for section in REQUIRED_SECTIONS]
        if any(position < 0 for position in positions) or positions != sorted(positions):
            markdown_failures.append(f"sections:{index_path}")
        machine_files = extract_machine_paths(generated, FILE_MARKER)
        machine_dirs = extract_machine_paths(generated, DIR_MARKER)
        expected_files = [item["path"] for item in record["direct_files"]]
        expected_dirs = [item["path"] for item in record["child_directories"]]
        if machine_files != expected_files:
            raise IndexErrorDetail(f"Direct file machine entries differ: {index_path}")
        if machine_dirs != expected_dirs:
            raise IndexErrorDetail(f"Child directory machine entries differ: {index_path}")
        file_coverage.update(machine_files)
        child_coverage.update(machine_dirs)
        secret_findings += len(SENSITIVE_VALUE_RE.findall(text))
        directory_semantics = (
            record.get("directory_role", ""),
            *(item.get("content_scope", "") for item in record["child_directories"]),
            *(item.get("when_to_enter", "") for item in record["child_directories"]),
        )
        if any(
            not str(value).strip()
            or GENERIC_RE.search(str(value))
            or GENERIC_SEMANTIC_RE.search(str(value))
            for value in directory_semantics
        ):
            generic_findings.append(f"directory:{directory or '<root>'}")
        for child in record["child_directories"]:
            if child.get("load_policy") not in {
                "do_not_load_by_default",
                "task_triggered_lazy_load",
            }:
                raise IndexErrorDetail(f"Invalid child load policy: {child['path']}")
        for item in record["direct_files"]:
            if item["authority_class"] not in AUTHORITY_CLASSES:
                raise IndexErrorDetail(f"Invalid authority class for {item['path']}")
            for field in (
                "content_summary",
                "role_and_use",
                "status_or_freshness",
                "when_to_read",
                "description_basis",
            ):
                if not str(item.get(field, "")).strip():
                    raise IndexErrorDetail(f"Empty {field} for {item['path']}")
            if any(
                GENERIC_RE.search(str(item[field]))
                or GENERIC_SEMANTIC_RE.search(str(item[field]))
                for field in (
                    "content_summary",
                    "role_and_use",
                    "status_or_freshness",
                    "when_to_read",
                )
            ):
                generic_findings.append(item["path"])
            if item["authority_class"] == "unknown_requires_review" and "复核" not in (
                item["content_summary"] + item["status_or_freshness"]
            ):
                raise IndexErrorDetail(
                    f"Unknown entry lacks explicit review reason: {item['path']}"
                )
        for item in record["direct_files"]:
            target = item["path"]
            relative = posixpath.relpath(target, directory or ".")
            if relative.startswith("../") or relative.startswith("/") or "\\" in relative:
                unsafe_links.append(f"{index_path}->{target}")
            if target not in all_file_paths:
                broken_links.append(f"{index_path}->{target}")
        for item in record["child_directories"]:
            target = index_path_for_directory(item["path"])
            relative = posixpath.relpath(target, directory or ".")
            if relative.startswith("../") or relative.startswith("/") or "\\" in relative:
                unsafe_links.append(f"{index_path}->{target}")
            if item["path"] not in all_directory_paths or target not in all_file_paths:
                broken_links.append(f"{index_path}->{target}")
    missing_files = sorted(path for path in all_file_paths if file_coverage[path] != 1)
    extra_files = sorted(path for path in file_coverage if path not in all_file_paths)
    non_root_dirs = all_directory_paths - {""}
    missing_dirs = sorted(path for path in non_root_dirs if child_coverage[path] != 1)
    extra_dirs = sorted(path for path in child_coverage if path not in non_root_dirs)
    if any((missing_files, extra_files, missing_dirs, extra_dirs)):
        raise IndexErrorDetail(
            "Coverage mismatch: "
            f"missing_files={missing_files[:10]} extra_files={extra_files[:10]} "
            f"missing_dirs={missing_dirs[:10]} extra_dirs={extra_dirs[:10]}"
        )
    if markdown_failures or unsafe_links or broken_links or generic_findings or secret_findings:
        raise IndexErrorDetail(
            f"Validation failures: markdown={markdown_failures[:5]} unsafe={unsafe_links[:5]} "
            f"broken={broken_links[:5]} generic={generic_findings[:5]} secrets={secret_findings}"
        )
    private_records = [
        item
        for record in manifest["directories"]
        for item in record["direct_files"]
        if path_is_private(item["path"]) and not path_is_index(item["path"])
    ]
    if any(item["description_basis"] != "restricted_private_metadata_only" for item in private_records):
        raise IndexErrorDetail("Private Zones content was not metadata-only")
    if any(path.startswith((".git/", ".ssh/")) for path in all_file_paths):
        raise IndexErrorDetail("Git internal or ignored SSH content entered inventory")
    return {
        "status": "pass",
        "ref": ref or "git-index-and-worktree",
        "tracked_directories": len(all_directory_paths),
        "index_files": len(actual_index_paths),
        "tracked_files": len(all_file_paths),
        "direct_file_entries": sum(file_coverage.values()),
        "child_directory_entries": sum(child_coverage.values()),
        "missing_file_entries": 0,
        "duplicate_file_entries": 0,
        "missing_child_directory_entries": 0,
        "duplicate_child_directory_entries": 0,
        "orphan_index_files": 0,
        "broken_relative_links": 0,
        "unsafe_absolute_links": 0,
        "git_internal_directories_indexed": 0,
        "secret_value_findings": 0,
        "utf8_parse_failures": 0,
        "markdown_structure_failures": 0,
        "empty_or_generic_descriptions": 0,
        "manual_index_sections": manifest["counts"]["manual_index_sections"],
        "hashes": manifest["hashes"],
    }


def check_outputs(ref: str | None) -> dict[str, Any]:
    expected, manifest = build_expected(ref)
    entries = load_git_entries(ref)
    blobs = load_blobs(entries)
    mismatches = []
    for path, expected_bytes in expected.items():
        actual = read_output(path, ref, entries, blobs)
        if actual != expected_bytes:
            mismatches.append(path)
    if mismatches:
        raise IndexErrorDetail(f"Deterministic check differs: {mismatches[:20]}")
    return {
        "status": "pass",
        "ref": ref or "git-index-and-worktree",
        "checked_outputs": len(expected),
        "hashes": manifest["hashes"],
    }


def snapshot(ref: str | None) -> dict[str, Any]:
    outputs, manifest = build_expected(ref)
    bundle_hash = sha256_records(
        path.encode("utf-8") + b"\0" + outputs[path] + b"\0"
        for path in sorted(outputs, key=unicode_sort_key)
    )
    return {
        "schema_version": SCHEMA_VERSION,
        "ref": ref or "git-index",
        "output_count": len(outputs),
        "output_bundle_sha256": bundle_hash,
        "manifest_sha256": hashlib.sha256(outputs[MANIFEST_PATH]).hexdigest(),
        "hashes": manifest["hashes"],
    }


def expect_error(function: Any, *args: Any, **kwargs: Any) -> None:
    try:
        function(*args, **kwargs)
    except IndexErrorDetail:
        return
    raise AssertionError("Expected fail-closed error")


def self_test() -> dict[str, Any]:
    block = "# generated\n"
    manual = "# 人工说明\r\n保持原样\r\n".encode("utf-8")
    merged, preserved = merge_generated_block("index.md", manual, block)
    assert preserved == manual and merged.startswith(manual)
    existing = (
        b"prefix\r\n"
        + START_MARKER.encode("ascii")
        + b"\nold\n"
        + END_MARKER.encode("ascii")
        + b"\r\nsuffix\r\n"
    )
    merged, preserved = merge_generated_block("index.md", existing, block)
    assert preserved == b"prefix\r\n\r\nsuffix\r\n"
    assert merged.startswith(b"prefix\r\n") and merged.endswith(b"\r\nsuffix\r\n")
    malformed = [
        START_MARKER.encode("ascii"),
        END_MARKER.encode("ascii"),
        END_MARKER.encode("ascii") + START_MARKER.encode("ascii"),
        START_MARKER.encode("ascii") * 2 + END_MARKER.encode("ascii"),
        b"```\n" + START_MARKER.encode("ascii") + b"\n```\n" + END_MARKER.encode("ascii"),
        b"inline `" + START_MARKER.encode("ascii") + b"`\n" + END_MARKER.encode("ascii") + b"\n",
        b"    " + START_MARKER.encode("ascii") + b"\n    " + END_MARKER.encode("ascii") + b"\n",
        b"<pre>\n" + START_MARKER.encode("ascii") + b"\n" + END_MARKER.encode("ascii") + b"\n</pre>\n",
        b"> " + START_MARKER.encode("ascii") + b"\n> " + END_MARKER.encode("ascii") + b"\n",
        b"<!-- outer\n" + START_MARKER.encode("ascii") + b"\n" + END_MARKER.encode("ascii") + b"\n-->\n",
        b"\xff\xfeinvalid",
    ]
    for data in malformed:
        expect_error(manual_bytes_and_marker_state, "index.md", data)
    samples = ["含 空格.md", "括号(样例).md", "中文路径/文件.yaml"]
    for sample in samples:
        encoded = markdown_link_target(sample)
        assert " " not in encoded and "(" not in encoded and ")" not in encoded
        assert "\\" not in encoded
    assert object_type_for_mode("120000") == "symlink"
    assert object_type_for_mode("160000") == "commit"
    unsafe_paths = [
        b"../escape",
        b"a/./b",
        b"a//b",
        b"line\nbreak",
        b"tab\tname",
        b"trailing.",
        b"stream:name",
        b"CON.txt",
        b"tick`name",
        b"html<name>.md",
    ]
    for raw_path in unsafe_paths:
        expect_error(decode_git_path, raw_path)
    sanitized_probe = "GIT_INDEX_FILE"
    previous_probe = os.environ.get(sanitized_probe)
    os.environ[sanitized_probe] = "caller-controlled-index"
    try:
        assert sanitized_probe not in sanitized_git_environment()
    finally:
        if previous_probe is None:
            os.environ.pop(sanitized_probe, None)
        else:
            os.environ[sanitized_probe] = previous_probe
    escaped = safe_text("<script>[x](javascript:alert(1))</script>|`code`")
    assert "<script>" not in escaped and "[x]" not in escaped and "`" not in escaped
    xml_failure = extract_xml("broken.xml", b"<broken>")
    assert xml_failure["summary"] == "XML 解析失败；解析器文案未写入索引，需人工复核"
    manual_marker = (
        b"manual <!-- RIDX_FILE_HEX 626164 -->\r\n"
        + START_MARKER.encode("ascii")
        + b"\n<!-- RIDX_FILE_HEX 676f6f64 -->\n"
        + END_MARKER.encode("ascii")
        + b"\r\n"
    )
    assert extract_machine_paths(
        generated_block_bytes("index.md", manual_marker), FILE_MARKER
    ) == ["good"]
    filesystem_cases = 0
    with tempfile.TemporaryDirectory(prefix="repository-index-self-test-") as temp:
        test_root = Path(temp).resolve()
        plain = safe_output_target("nested/index.md", root=test_root)
        assert plain == test_root / "nested" / "index.md"
        filesystem_cases += 1
        special = test_root / "special"
        special.mkdir()
        expect_error(safe_output_target, "special", root=test_root)
        filesystem_cases += 1
        source = test_root / "source.txt"
        source.write_bytes(b"x")
        hardlink = test_root / "hardlink.txt"
        os.link(source, hardlink)
        expect_error(safe_output_target, "hardlink.txt", root=test_root)
        filesystem_cases += 1
        symlink = test_root / "symlink.txt"
        try:
            symlink.symlink_to(source)
        except OSError:
            pass
        else:
            expect_error(safe_output_target, "symlink.txt", root=test_root)
            filesystem_cases += 1
    return {
        "status": "pass",
        "manual_preservation_cases": 2,
        "malformed_marker_fail_closed_cases": len(malformed),
        "markdown_link_cases": len(samples),
        "special_git_mode_cases": 2,
        "unsafe_git_path_fail_closed_cases": len(unsafe_paths),
        "safe_text_html_injection_cases": 1,
        "xml_runtime_message_exclusion_cases": 1,
        "manual_machine_marker_scope_cases": 1,
        "filesystem_link_boundary_cases": filesystem_cases,
        "git_environment_sanitization_cases": 1,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("generate")
    for name in ("check", "validate", "snapshot"):
        child = subparsers.add_parser(name)
        child.add_argument("--ref", default=None)
    subparsers.add_parser("self-test")
    args = parser.parse_args()
    try:
        if args.command == "generate":
            outputs, manifest = build_expected(None)
            changed = write_outputs(outputs)
            result = {
                "status": "generated",
                "changed_outputs": len(changed),
                "changed_paths": changed,
                "counts": manifest["counts"],
                "hashes": manifest["hashes"],
            }
        elif args.command == "check":
            result = check_outputs(args.ref)
        elif args.command == "validate":
            result = validate_outputs(args.ref)
        elif args.command == "snapshot":
            result = snapshot(args.ref)
        else:
            result = self_test()
    except (IndexErrorDetail, AssertionError, json.JSONDecodeError) as exc:
        print(json.dumps({"status": "failed", "error": str(exc)}, ensure_ascii=False))
        return 1
    print(json.dumps(result, ensure_ascii=False, sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
